// Helper to generate mock observations for any state fallback
export function generateStateMockObservations(stateCode: string): Observation[] {
  const state = US_STATES.find((s) => s.code.toLowerCase() === stateCode.toLowerCase());
  if (!state) return NATIONWIDE_NOTABLE_OBSERVATIONS;

  const [cLat, cLng] = state.center;
  const sampleSpecies = [
    { comName: 'American Crow', sciName: 'Corvus brachyrhynchos', code: 'amecro', count: 320, isRoost: true },
    { comName: 'Bald Eagle', sciName: 'Haliaeetus leucocephalus', code: 'baleag', count: 3, isRoost: false },
    { comName: 'Red-tailed Hawk', sciName: 'Buteo jamaicensis', code: 'rethaw', count: 5, isRoost: false },
    { comName: 'Peregrine Falcon', sciName: 'Falco peregrinus', code: 'perfal', count: 2, isRoost: false },
    { comName: 'Great Blue Heron', sciName: 'Ardea herodias', code: 'grbher3', count: 8, isRoost: false },
    { comName: 'Northern Cardinal', sciName: 'Cardinalis cardinalis', code: 'norcar', count: 16, isRoost: false },
    { comName: 'Blue Jay', sciName: 'Cyanocitta cristata', code: 'blujay', count: 22, isRoost: false },
    { comName: 'Osprey', sciName: 'Pandion haliaetus', code: 'osprey', count: 4, isRoost: false },
    { comName: 'Wood Duck', sciName: 'Aix sponsa', code: 'wooduc', count: 14, isRoost: false },
    { comName: 'American Goldfinch', sciName: 'Spinus tristis', code: 'amegfi', count: 35, isRoost: false },
  ];

  return sampleSpecies.map((sp, idx) => {
    // Generate scattered points around state center
    const latOffset = (Math.sin(idx * 1.7) * 0.45) * (state.zoom < 7 ? 1.8 : 0.8);
    const lngOffset = (Math.cos(idx * 2.3) * 0.55) * (state.zoom < 7 ? 1.8 : 0.8);
    const obsLat = Number((cLat + latOffset).toFixed(4));
    const obsLng = Number((cLng + lngOffset).toFixed(4));

    return {
      id: `${state.code.toLowerCase()}-obs-${idx + 1}`,
      speciesCode: sp.code,
      comName: sp.comName,
      sciName: sp.sciName,
      locId: `L-${state.code}-${idx + 100}`,
      locName: `${state.name} State Park & Wildlife Refuge`,
      obsDt: 'Today ' + (8 + (idx % 6)) + ':30 AM',
      howMany: sp.count,
      lat: obsLat,
      lng: obsLng,
      obsReviewed: true,
      subId: `S-${state.code}-${idx}`,
      isCrowRoost: sp.isRoost,
      notes: `Observed foraging and transit flock in ${state.name} regional wildlife sector.`,
    };
  });
}
